
import { prisma } from "@/lib/prisma";
import { FileText, Code, FileCode, Search, Download } from "lucide-react";

export const dynamic = "force-dynamic";

export default async function ContentLibrary() {
  const files = await prisma.generatedFile.findMany({
    orderBy: { updatedAt: "desc" }
  });

  return (
    <div className="p-8 max-w-[1200px] mx-auto min-h-screen text-slate-200">
      <h1 className="text-[36px] font-black tracking-[-0.04em] mb-2 text-white">Content Library</h1>
      <p className="text-slate-400 font-medium mb-10">
        Review scripts and documents generated by your Hermes agents.
      </p>

      <div className="grid grid-cols-1 gap-6">
        {files.length === 0 ? (
           <div className="p-20 text-center border-2 border-dashed border-white/10 rounded-3xl text-slate-500 font-bold uppercase tracking-widest">
             No content indexed yet. Run the content_indexer.py script.
           </div>
        ) : (
          files.map((file) => (
            <div key={file.id} className="rounded-2xl border border-white/10 overflow-hidden bg-slate-900/30">
              <div className="p-4 bg-white/5 border-b border-white/10 flex items-center justify-between">
                <div className="flex items-center gap-3">
                  <div className="p-2 bg-cyan-500/10 rounded-lg text-cyan-400">
                    {file.extension === '.py' ? <Code size={18} /> : <FileText size={18} />}
                  </div>
                  <div>
                    <div className="text-[14px] font-bold text-white">{file.name}</div>
                    <div className="text-[10px] font-bold text-slate-500 uppercase tracking-tighter">{file.path}</div>
                  </div>
                </div>
                <div className="text-[11px] font-black text-cyan-400 px-3 py-1 bg-cyan-500/10 rounded-full">
                   {(file.size / 1024).toFixed(1)} KB
                </div>
              </div>
              <div className="p-5 overflow-x-auto">
                <pre className="text-[12px] font-mono text-slate-300 leading-relaxed whitespace-pre-wrap">
                  {file.content || "// No preview available"}
                </pre>
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
}
